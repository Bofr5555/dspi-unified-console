#!/bin/bash
# WP WB7: upstream's DSPi-Link web page, built unmodified from the pinned source, for
# `dspi hub --web` to serve at /hub/ (crates/dspi-hub/src/web.rs).
#
#   crates/dspi-hub/tools/build-link-web.sh           build and write the bundle
#   crates/dspi-hub/tools/build-link-web.sh --check   build and compare with it
#
# The source is the commit the conformance run already pins (DSPI_LINK_COMMIT in
# tests/conformance/run-clients.sh), taken from the clone in
# work/consoles/DSPi-Link with `git archive`, its `js` tree checked by hash. It is
# built with npm ci from its own lockfile (integrity hashes, --ignore-scripts) and
# Vite in the official Node image pinned by digest (NODE in images.conf). The build
# is reproducible: --check rebuilds and compares byte for byte.
#
# Writes crates/dspi-hub/assets/web/hub/: the control page (index.html) and the
# files it loads, unchanged; LICENSE (DSPi-Link's, MIT); PROVENANCE.json (source,
# image, sha256 of every file). And src/link_web.rs, the table web.rs serves from.
# Left out: setup.html and its files, the bridge's Wi-Fi setup page, which calls a
# /setup/v1 API that only a bridge has.
set -euo pipefail
root=$(cd "$(dirname "$0")/../../.." && pwd)
. "$root/ci/container/images.conf"
B=${DSPI_BUILD_CACHE:-$HOME/.cache/dspi-build}
DSPI_LINK_REPO=${DSPI_LINK_REPO:-$B/work/consoles/DSPi-Link}
DSPI_LINK_COMMIT=86f10e38dd760d01d4f589e4b606a5250b2d523d
# git rev-parse 86f10e38:js (the client library, the web app and their lockfile)
DSPI_LINK_JS_TREE=128dca29d020ff7d709c35f422573fef0083df7e
check=0
[ "${1:-}" = --check ] && check=1

got=$(git -C "$DSPI_LINK_REPO" rev-parse "$DSPI_LINK_COMMIT:js")
[ "$got" = "$DSPI_LINK_JS_TREE" ] || { echo "build-link-web: upstream js tree $got, expected $DSPI_LINK_JS_TREE" >&2; exit 1; }
work=$B/work/link-web
rm -rf "$work/src" "$work/out"
mkdir -p "$work/src" "$work/out" "$work/npm" "$work/home"
git -C "$DSPI_LINK_REPO" archive "$DSPI_LINK_COMMIT" js LICENSE | tar -x -C "$work/src"
podman image exists "$NODE" || podman pull -q "$NODE" >/dev/null
podman run --rm --init --userns=keep-id --user "$(id -u):$(id -g)" \
  -v "$work/src":/w:z -v "$work/npm":/npm:z -v "$work/home":/home/n:z \
  -e HOME=/home/n -e npm_config_cache=/npm -e npm_config_update_notifier=false \
  -w /w/js "$NODE" bash -euo pipefail -c '
    npm ci --no-audit --no-fund --ignore-scripts
    npm run build'

python3 - "$work" "$root" "$check" "$DSPI_LINK_COMMIT" "$DSPI_LINK_JS_TREE" "$NODE" <<'PY'
import hashlib, json, re, shutil, sys
from pathlib import Path
work, root, check, commit, tree, image = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3] == "1", *sys.argv[4:]
dist = work / "src/js/apps/web/dist"
out = work / "out"
# index.html and what it loads, then what those import, transitively.
wanted, queue = ["index.html"], ["index.html"]
while queue:
    text = (dist / queue.pop()).read_text()
    for ref in re.findall(r'(?:src|href)="\./(assets/[^"]+)"|from"\./([^"]+\.js)"|import\("\./([^"]+\.js)"\)', text):
        rel = next(r for r in ref if r)
        rel = rel if rel.startswith("assets/") else f"assets/{rel}"
        if rel not in wanted and (dist / rel).is_file():
            wanted.append(rel)
            if rel.endswith(".js"):
                queue.append(rel)
files = {}
for rel in sorted(wanted):
    (out / rel).parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(dist / rel, out / rel)
    files[rel] = hashlib.sha256((dist / rel).read_bytes()).hexdigest()
shutil.copyfile(work / "src/LICENSE", out / "LICENSE")
lock = json.loads((work / "src/js/package-lock.json").read_text())
web = json.loads((work / "src/js/apps/web/package.json").read_text())
provenance = {
    "what": "DSPi-Link js/apps/web (@dspi/web), the control page a hub serves, built unmodified",
    "repository": "https://github.com/WeebLabs/DSPi-Link",
    "commit": commit,
    "js_tree": tree,
    "version": web["version"],
    "license": "MIT",
    "build": f"npm ci --ignore-scripts && npm run build, in {image}",
    "left_out": "setup.html and its assets (the bridge's Wi-Fi setup page)",
    # What the page's bundle is made of: the lockfile's packages that are not dev-only
    # (the workspace's own, @dspi/link and @dspi/web, both upstream's).
    "bundled_packages": sorted(
        f"{v.get('name') or p.rsplit('node_modules/', 1)[-1]} {v.get('version', '')} {v.get('license', 'no licence field')}"
        for p, v in lock["packages"].items() if p and not v.get("dev") and not v.get("link")
    ),
    "files": files,
}
(out / "PROVENANCE.json").write_text(json.dumps(provenance, indent=1, sort_keys=True) + "\n")

kinds = {".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8"}
lines = [
    "// Generated by crates/dspi-hub/tools/build-link-web.sh (WP WB7); do not edit.",
    "// Upstream's DSPi-Link web page, built unmodified: assets/web/hub/PROVENANCE.json.",
    "",
    "use super::Asset;",
    "",
    "/// The page's files by request path, under `/hub/`.",
    "pub(super) const FILES: &[(&str, Asset)] = &[",
]
for rel in sorted(files):
    path = "/hub/" if rel == "index.html" else f"/hub/{rel}"
    kind = kinds[Path(rel).suffix]
    lines += [
        "    (",
        f'        "{path}",',
        "        Asset {",
        f'            content_type: "{kind}",',
        f'            body: include_bytes!("../assets/web/hub/{rel}"),',
        "        },",
        "    ),",
    ]
lines += ["];", ""]
generated = "\n".join(lines)

dest = root / "crates/dspi-hub/assets/web/hub"
gen = root / "crates/dspi-hub/src/link_web.rs"
if check:
    same = gen.is_file() and gen.read_text() == generated
    for f in sorted(p for p in out.rglob("*") if p.is_file()):
        rel = f.relative_to(out)
        same = same and (dest / rel).is_file() and (dest / rel).read_bytes() == f.read_bytes()
    committed = sorted(str(p.relative_to(dest)) for p in dest.rglob("*") if p.is_file()) if dest.exists() else []
    same = same and committed == sorted(str(p.relative_to(out)) for p in out.rglob("*") if p.is_file())
    print("build-link-web: the bundle matches its source" if same else "build-link-web: the bundle differs from a fresh build", file=sys.stderr)
    sys.exit(0 if same else 1)
shutil.rmtree(dest, ignore_errors=True)
shutil.copytree(out, dest)
gen.write_text(generated)
print(f"build-link-web: wrote {dest.relative_to(root)} ({len(files)} files) and {gen.relative_to(root)}")
PY
