#!/usr/bin/env python3
"""The bundled-firmware manifest and its CI digest check (WP SECFWV, OD-SECn).

    tools/firmware_manifest.py            write firmware/manifest.json
    tools/firmware_manifest.py --check    fail unless the manifest is current and
                                          every bundle matches it (ci/check.sh
                                          --step firmware-digests)
    --root DIR                            another tree laid out the same (tests)

The source of truth is the SHA-256 the Android supply-chain test pins
(Uf2ImageTest.bundledAssetsAreTheVerifiedOfficialRelease), which were checked
against the digests GitHub publishes for the release (apps/android/docs/
SUPPLY-CHAIN.md). The manifest lists those images; --check then demands that the
Android, Qt and Apple bundles each hold exactly those files, byte for byte.

What the manifest is NOT: tamper protection. It ships inside the same bundle as
the images, so whoever swaps a .uf2 can swap the manifest too. It catches build
mix-ups and corruption. The real controls are platform code signing and this CI
check, which compares every app's bundle against the pinned digests.

Stdlib only; runs on the host like the licences step.
"""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

PINS = "apps/android/feature-firmware/src/test/kotlin/se/bofr/dspi/feature/firmware/Uf2ImageTest.kt"
MANIFEST = "firmware/manifest.json"
BUNDLES = {
    "android": "apps/android/feature-firmware/src/main/assets/firmware",
    "qt": "apps/desktop/qt/firmware",
    "apple": "apps/apple/DSPi Console/Firmware",
}
# assertEquals("<sha256>", sha256(Assets.read("<name>")))
PIN_RE = re.compile(
    r'assertEquals\(\s*"([0-9a-fA-F]{64})"\s*,\s*sha256\(\s*Assets\.read\(\s*"([^"]+\.uf2)"\s*\)\s*\)\s*\)'
)
NAME_RE = re.compile(r"^DSPi-(RP2040|RP2350)-v(\d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?)\.uf2$")
ABOUT = (
    "SHA-256 of every firmware image the apps bundle, generated by tools/firmware_manifest.py "
    "from the digests pinned in the Android supply-chain test. A consistency check against "
    "build mix-ups and corruption, NOT tamper protection: it ships in the same bundle as the "
    "images. The real controls are platform code signing and the CI digest test "
    "(ci/check.sh --step firmware-digests)."
)


class ManifestError(Exception):
    """The pins or the Android assets they pin are not usable."""


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def image_version(data: bytes, version: str) -> str:
    """The DSPi version string inside the image (`1.1.6-1-g9ffce34`, no `v`),
    the one the core's uf2_inspect reports, which the core's test checks.
    Found in the payload reassembled from the UF2 blocks."""
    payload = bytearray()
    for off in range(0, len(data) - 511, 512):
        size = int.from_bytes(data[off + 16:off + 20], "little")
        payload += data[off + 32:off + 32 + min(size, 476)]
    pattern = re.compile(rb"v(" + re.escape(version.encode()) + rb"(?:-[0-9A-Za-z.+-]+)?)\x00")
    found = sorted({m.group(1).decode() for m in pattern.finditer(bytes(payload))})
    if len(found) != 1:
        raise ManifestError(f"version {version}: expected one version string in the image, found {found}")
    return found[0]


def pins(root: Path) -> list:
    text = (root / PINS).read_text(encoding="utf-8")
    found = [(name, digest.lower()) for digest, name in PIN_RE.findall(text)]
    if not found:
        raise ManifestError(f"no pinned digests found in {PINS}")
    names = [n for n, _ in found]
    if len(set(names)) != len(names):
        raise ManifestError(f"a name is pinned twice in {PINS}")
    return sorted(found)


def build(root: Path) -> dict:
    """The manifest, from the pins and the Android assets they pin."""
    images = []
    for name, digest in pins(root):
        m = NAME_RE.match(name)
        if not m:
            raise ManifestError(f"{name}: not DSPi-<chip>-v<version>.uf2")
        path = root / BUNDLES["android"] / name
        if not path.is_file():
            raise ManifestError(f"{name} is pinned but missing from {BUNDLES['android']}")
        actual = sha256(path)
        if actual != digest:
            raise ManifestError(
                f"{BUNDLES['android']}/{name} is {actual}, the pin says {digest}"
            )
        images.append(
            {
                "name": name,
                "platform": m.group(1),
                "version": image_version(path.read_bytes(), m.group(2)),
                "size": path.stat().st_size,
                "sha256": digest,
            }
        )
    return {"_about": ABOUT, "pins": PINS, "bundles": sorted(BUNDLES.values()), "images": images}


def render(manifest: dict) -> str:
    return json.dumps(manifest, indent=2) + "\n"


def check(root: Path) -> list:
    problems = []
    try:
        manifest = build(root)
    except ManifestError as e:
        return [f"android: {e}"]
    path = root / MANIFEST
    if not path.is_file():
        problems.append(f"{MANIFEST} is missing")
    elif path.read_text(encoding="utf-8") != render(manifest):
        problems.append(f"{MANIFEST} is not current")
    want = {e["name"]: e["sha256"] for e in manifest["images"]}
    for app, rel in BUNDLES.items():
        d = root / rel
        if not d.is_dir():
            problems.append(f"{app}: {rel} is missing")
            continue
        have = {p.name: p for p in d.iterdir() if p.name.lower().endswith(".uf2")}
        for name in sorted(set(want) - set(have)):
            problems.append(f"{app}: {rel}/{name} is missing")
        for name in sorted(set(have) - set(want)):
            problems.append(f"{app}: {rel}/{name} is not in the manifest (pin it in {PINS} first)")
        for name in sorted(set(want) & set(have)):
            actual = sha256(have[name])
            if actual != want[name]:
                problems.append(f"{app}: {rel}/{name} is {actual}, the manifest says {want[name]}")
    return problems


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    args = ap.parse_args(argv)
    root = args.root
    try:
        return run(root, args.check)
    except ManifestError as e:
        print(f"firmware-digests: {e}", file=sys.stderr)
        return 1


def run(root: Path, check_only: bool) -> int:
    if check_only:
        problems = check(root)
        for p in problems:
            print(f"firmware-digests: {p}", file=sys.stderr)
        if problems:
            print("firmware-digests: FAILED. To regenerate after a deliberate bump: tools/firmware_manifest.py",
                  file=sys.stderr)
            return 1
        n = len(build(root)["images"])
        print(f"firmware-digests: {n} images, the manifest and all {len(BUNDLES)} bundles agree")
        return 0
    (root / MANIFEST).parent.mkdir(parents=True, exist_ok=True)
    (root / MANIFEST).write_text(render(build(root)), encoding="utf-8")
    print(f"wrote {MANIFEST}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
