#!/usr/bin/env python3
"""The third-party notices of the Rust crates in the Terminal's binary (WP CLEAN1).

Writes apps/terminal/notices/rust-crates.txt: every crate linked into the Terminal
(`-p dspi-term`, default features: the normal, non-proc-macro closure), its licence
expression and the licence and notice files it ships, identical texts printed once.
The union over the targets the release archives are built for, so a crate may be
linked on only some of them. The binary embeds it (`uconsole --third-party-licences`)
and ci/release-terminal.sh puts it into each archive as THIRD-PARTY-NOTICES.txt. Modelled on
apps/desktop/packaging/licences/gen_rust_notices.py. Runs in the build container:

    ci/run.sh 'python3 apps/terminal/tools/gen_rust_notices.py'
    ci/run.sh 'python3 apps/terminal/tools/gen_rust_notices.py --check'

ci/check.sh's terminal step runs --check, which fails when the committed file is stale.
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

TOP = Path(__file__).resolve().parents[3]
OUT = TOP / "apps/terminal/notices/rust-crates.txt"
SELECT = ["-p", "dspi-term"]
TARGETS = ("x86_64-unknown-linux-gnu", "aarch64-unknown-linux-gnu", "x86_64-pc-windows-msvc",
           "aarch64-apple-darwin", "x86_64-apple-darwin")
TITLE = "Third-party Rust crates linked into the DSPi Terminal (the uConsole command)\n"
SCOPE = "The union for Linux (x86_64, aarch64), Windows and macOS: a crate may be linked on only some of them.\n"

# File-name prefixes of licence and notice files, matched case-insensitively:
# the windows-* crates ship `license-mit` and `license-apache-2.0`.
NOTICE_PREFIXES = ("license", "licence", "copying", "notice", "unlicense", "copyright")

# A crate that ships no licence file (objc2, block2, objc2-encode) still needs its
# notice with the binary: for MIT, the standard text with the authors cargo
# records. Any other crate without a file fails the run.
MIT_TEXT = """Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE.
"""


def crate_closure():
    pkgs = {}
    for target in TARGETS:
        tree = subprocess.check_output(
            ["cargo", "tree", "--locked", *SELECT, "--target", target,
             "-e", "normal,no-proc-macro", "--prefix", "none", "--no-dedupe", "-f", "{p}"],
            cwd=TOP, text=True)
        wanted = {tuple(ln.split()[:2]) for ln in tree.splitlines() if ln.strip()}
        meta = json.loads(subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
            cwd=TOP))
        found = {(p["name"], "v" + p["version"]): p for p in meta["packages"] if (p["name"], "v" + p["version"]) in wanted}
        missing = wanted - set(found)
        if missing:
            sys.exit(f"{target}: cargo tree lists crates cargo metadata does not: {sorted(missing)}")
        pkgs.update(found)
    return sorted(pkgs.values(), key=lambda p: (p["name"], p["version"]))


def notice_files(pkg):
    d = Path(pkg["manifest_path"]).parent
    return sorted(f for f in d.iterdir()
                  if f.is_file() and f.name.lower().startswith(NOTICE_PREFIXES))


def fallback_text(pkg):
    """The notice of a crate without a licence file, or None if there is none to give."""
    words = (pkg.get("license") or "").replace("(", " ").replace(")", " ").split()
    if "MIT" not in words:
        return None
    authors = ", ".join(pkg.get("authors") or []) or f"the {pkg['name']} authors"
    return (f"(The crate ships no licence file; its Cargo.toml declares {pkg.get('license')}.\n"
            f"The MIT licence, with the authors it names:)\n\nCopyright (c) {authors}\n\n" + MIT_TEXT)


def main():
    out, texts, textless = [], {}, []
    out.append(TITLE)
    out.append("Generated by apps/terminal/tools/gen_rust_notices.py; do not edit.\n")
    out.append(SCOPE)
    out.append("Where a crate offers a choice (\"MIT OR Apache-2.0\"), this program uses it under the\n"
               "licence compatible with GPL-3.0 (MIT or Apache-2.0).\n\n")
    for p in crate_closure():
        # This project's own (dspi-*): uConsole for DSPi's licence, `--license` and NOTICE.md
        if Path(p["manifest_path"]).resolve().is_relative_to(TOP):
            continue
        lic = p.get("license") or "(see files)"
        repo = p.get("repository") or ""
        out.append("=" * 72 + "\n")
        out.append(f"{p['name']} {p['version']} — {lic}\n{repo}\n")
        files = notice_files(p)
        if not files:
            body = fallback_text(p)
            if body is None:
                textless.append(f"{p['name']} {p['version']} ({lic})")
            else:
                out.append(f"\n--- (no licence file) ---\n{body}")
        for f in files:
            body = f.read_text(errors="replace").strip() + "\n"
            h = hashlib.sha256(body.encode()).hexdigest()[:12]
            rel = f.relative_to(Path(p["manifest_path"]).parent)
            if h in texts:
                out.append(f"\n[{rel}: same text as {texts[h]}]\n")
            else:
                texts[h] = f"{p['name']} {p['version']}/{rel}"
                out.append(f"\n--- {rel} ---\n{body}")
        out.append("\n")
    # -- WP CLEAN1 fixup cl1 -- every crate in the binary carries a text
    if textless:
        sys.exit("crates with no licence text and no notice to give: " + ", ".join(textless))
    text = "".join(out)
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(TOP)} is stale: run apps/terminal/tools/gen_rust_notices.py")
        print(f"{OUT.relative_to(TOP)}: up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(TOP)} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
