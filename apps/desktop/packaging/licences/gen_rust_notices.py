#!/usr/bin/env python3
"""The third-party notices of the Rust crates in the desktop packages' core (WP LIC1).

Writes apps/desktop/packaging/licences/rust-crates.txt: every crate linked into
dspi_capi as the Qt packages build it (`-p dspi-capi --features link,midir,mdns,hub`,
the normal, non-proc-macro closure), its licence expression and the licence and
notice files it ships, identical texts printed once. One file for every desktop
package: the union of the closures for x86_64-unknown-linux-gnu (AppImage, .deb,
.rpm), x86_64-pc-windows-gnu (Windows) and aarch64-apple-darwin and
x86_64-apple-darwin (.dmg), so a crate may be in only some of them. stage.sh puts
it into LICENSES/ (AppImage, Windows, .dmg), qt/CMakeLists.txt next to the notice
(.deb, .rpm). Modelled on apps/web/tools/gen_rust_notices.py. Runs in the build
container (cargo and the crate registry):

    ci/run.sh 'python3 apps/desktop/packaging/licences/gen_rust_notices.py'
    ci/run.sh 'python3 apps/desktop/packaging/licences/gen_rust_notices.py --check'

ci/check.sh's qt step runs --check, which fails when the committed file is stale.

-- WP REL013M -- With --swift: apps/apple/licences/rust-crates.txt, the crates in
the Swift macOS app's core (`-p dspi-ffi`, default features, as
apps/apple/build-xcframework.sh builds its macOS slices) for aarch64-apple-darwin
and x86_64-apple-darwin. apps/apple/package-macos.sh puts it into the app's
LICENSES/; ci/check.sh's swift step runs --swift --check.
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

TOP = Path(__file__).resolve().parents[4]
SWIFT = "--swift" in sys.argv   # -- WP REL013M --
if SWIFT:
    OUT = TOP / "apps/apple/licences/rust-crates.txt"
    SELECT = ["-p", "dspi-ffi"]
    TARGETS = ("aarch64-apple-darwin", "x86_64-apple-darwin")
    TITLE = "Third-party Rust crates linked into DSPi Console's core (dspi_ffi) in the Swift macOS app\n"
    SCOPE = "The union for Apple silicon and Intel: a crate may be linked on only one of them.\n"
else:
    OUT = TOP / "apps/desktop/packaging/licences/rust-crates.txt"
    SELECT = ["-p", "dspi-capi", "--features", "link,midir,mdns,hub"]
    TARGETS = ("x86_64-unknown-linux-gnu", "x86_64-pc-windows-gnu", "aarch64-apple-darwin", "x86_64-apple-darwin")
    TITLE = "Third-party Rust crates linked into DSPi Console's core (dspi_capi) in the desktop packages\n"
    SCOPE = "The union for Linux, Windows and macOS: a crate may be linked on only some of them.\n"
NOTICE_GLOBS = ("LICENSE*", "LICENCE*", "COPYING*", "NOTICE*", "UNLICENSE*", "COPYRIGHT*")


def crate_closure():
    pkgs = {}
    for target in TARGETS:
        tree = subprocess.check_output(
            ["cargo", "tree", "--locked", *SELECT, "--target", target,
             "-e", "normal,no-proc-macro", "--prefix", "none", "--no-dedupe", "-f", "{p}"],
            cwd=TOP, text=True)
        wanted = {tuple(ln.split()[:2]) for ln in tree.splitlines() if ln.strip()}
        meta = json.loads(subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
            cwd=TOP))
        found = {(p["name"], "v" + p["version"]): p for p in meta["packages"] if (p["name"], "v" + p["version"]) in wanted}
        missing = wanted - set(found)
        if missing:
            sys.exit(f"{target}: cargo tree lists crates cargo metadata does not: {sorted(missing)}")
        pkgs.update(found)
    return sorted(pkgs.values(), key=lambda p: (p["name"], p["version"]))


def notice_files(pkg):
    d = Path(pkg["manifest_path"]).parent
    return sorted({f for g in NOTICE_GLOBS for f in d.glob(g) if f.is_file()})


def main():
    out, texts = [], {}
    out.append(TITLE)
    out.append("Generated by apps/desktop/packaging/licences/gen_rust_notices.py; do not edit.\n")
    out.append(SCOPE)
    out.append("Where a crate offers a choice (\"MIT OR Apache-2.0\"), this program uses it under the\n"
               "licence compatible with GPL-3.0 (MIT or Apache-2.0).\n\n")
    for p in crate_closure():
        # This project's own (dspi-*): DSPi Console's licence, in NOTICE.txt
        if Path(p["manifest_path"]).resolve().is_relative_to(TOP):
            continue
        lic = p.get("license") or "(see files)"
        repo = p.get("repository") or ""
        out.append("=" * 72 + "\n")
        out.append(f"{p['name']} {p['version']} — {lic}\n{repo}\n")
        for f in notice_files(p):
            body = f.read_text(errors="replace").strip() + "\n"
            h = hashlib.sha256(body.encode()).hexdigest()[:12]
            rel = f.relative_to(Path(p["manifest_path"]).parent)
            if h in texts:
                out.append(f"\n[{rel}: same text as {texts[h]}]\n")
            else:
                texts[h] = f"{p['name']} {p['version']}/{rel}"
                out.append(f"\n--- {rel} ---\n{body}")
        out.append("\n")
    text = "".join(out)
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(TOP)} is stale: run apps/desktop/packaging/licences/gen_rust_notices.py"
                     + (" --swift" if SWIFT else ""))
        print(f"{OUT.relative_to(TOP)}: up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(TOP)} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
