#!/usr/bin/env python3
"""Generate the Kotlin side of the core contract from the core's own modules.

Reads   crates/dspi-core/src/**/*.rs    what `cfg_attr(feature = "uniffi", ...)` marks:
                                        records, enums, objects, foreign traits, the error,
                                        `DspiCore` methods, free functions
        crates/dspi-core/src/consts.rs  constants the C header does not have
        crates/dspi-capi/src/types/consts.rs
                                        every old-core constant, as literals (a test there
                                        checks them against the firmware-generated values)
        crates/dspi-proto/firmware/config.h
                                        `REQ_*` opcodes newer than those
Writes  core-api/src/main/kotlin/se/bofr/dspi/core/CoreTypes.kt    (domain records)
        core-api/src/main/kotlin/se/bofr/dspi/core/DspiCoreApi.kt   (the interface)
        ffi/src/main/kotlin/se/bofr/dspi/ffi/FfiDspiCore.kt         (UniFFI adapter)
        core-api/.../UnimplementedDspiCore.kt, DspiConstants.kt

The outputs are checked in. `--check` exits 1 if they are stale (CI runs it),
so the core's exported surface, the Kotlin interface and the adapter cannot drift.
The UniFFI Kotlin itself is generated at build time, once per namespace
(ffi/build.gradle.kts), and the adapter is compiled against it, so a parse that
disagrees with what UniFFI exports fails the :ffi build.

Type rules (domain side, i.e. everything outside :ffi):
  u8 u16 i8 i16 i32 -> Int     u32 u64 i64 -> Long     f32 -> Float   f64 -> Double
  bool -> Boolean       String, &str -> String  Vec<u8> -> List<Int> (unsigned)
  Vec<u8> named bulk_raw -> ByteArray           Vec<T> -> List<T>
  Option<T> -> T?       Result<T> -> T, throws DspiException
  Arc<dyn L> -> L       Arc<Object> -> Object
Names: snake_case -> lowerCamelCase exactly as UniFFI does; flat enum variants
-> SCREAMING_SNAKE, also as UniFFI does.
"""
