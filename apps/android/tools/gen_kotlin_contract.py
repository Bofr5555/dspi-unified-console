def camel(s: str) -> str:
    parts = s.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


@dataclass
class Field:
    name: str
    ty: str
    doc: list[str] = field(default_factory=list)


@dataclass
class Record:
    name: str
    fields: list[Field]
    doc: list[str]


@dataclass
class Fn:
    name: str
    params: list[Field]
    ret: str | None
    doc: list[str]
    free: bool


@dataclass
class Variant:
    name: str
    fields: list[Field]
    doc: list[str]


@dataclass
class Enum:
    name: str
    variants: list[Variant]
    doc: list[str]


@dataclass
class Iface:
    """An exported object or foreign trait: named methods."""

    name: str
    methods: list[Fn]
    doc: list[str]


@dataclass
class Surface:
    records: list[Record] = field(default_factory=list)
    enums: list[Enum] = field(default_factory=list)
    error: Enum | None = None
    objects: dict[str, Iface] = field(default_factory=dict)
    traits: dict[str, Iface] = field(default_factory=dict)
    methods: list[Fn] = field(default_factory=list)
    free: list[Fn] = field(default_factory=list)


def split_top(s: str, sep: str = ",") -> list[str]:
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [x.strip() for x in out if x.strip()]


def parse_records(text: str) -> list[Record]:
    recs = []
    lines = text.splitlines()
    i = 0
    doc: list[str] = []
    while i < len(lines):
        ln = lines[i].strip()
        if ln.startswith("///"):
            doc.append(ln[3:].strip())
        elif ln.startswith("#["):
            pass
        elif m := re.match(r"pub struct (\w+) \{", ln):
            name, fields, fdoc = m.group(1), [], []
            i += 1
            while lines[i].strip() != "}":
                fl = lines[i].strip()
                if fl.startswith("///"):
                    fdoc.append(fl[3:].strip())
                elif fm := re.match(r"pub (\w+): (.+),$", fl):
                    fields.append(Field(fm.group(1), fm.group(2), fdoc))
                    fdoc = []
                elif fl.startswith("//"):
                    fdoc = []
                i += 1
            recs.append(Record(name, fields, doc))
            doc = []
        else:
            doc = []
        i += 1
    return recs


def parse_fns(text: str, free: bool) -> list[Fn]:
    fns = []
    doc: list[str] = []
    lines = text.splitlines(keepends=True)
    i = 0
    while i < len(lines):
        ln = lines[i].strip()
        if ln.startswith("///"):
            doc.append(ln[3:].strip())
            i += 1
            continue
        if ln.startswith("#["):
            if "uniffi::constructor" in ln:
                doc = ["__ctor__"]
            i += 1
            continue
        if ln.startswith("pub fn "):
            # Collect the signature up to the opening brace.
            sig = ""
            j = i
            while "{" not in lines[j]:
                sig += lines[j].strip() + " "
                j += 1
            sig += lines[j].split("{")[0].strip()
            m = re.match(r"pub fn (\w+)\((.*)\)\s*(?:->\s*(.+?))?\s*$", sig.strip())
            if not m:
                raise SystemExit(f"cannot parse signature: {sig}")
            name, args, ret = m.group(1), m.group(2), m.group(3)
            params = []
            for a in split_top(args):
                if a in ("&self", "self"):
                    continue
                pn, pt = a.split(":", 1)
                params.append(Field(pn.strip(), pt.strip()))
            if doc != ["__ctor__"] and (free or "&self" in args):
                fns.append(Fn(name, params, ret.strip() if ret else None, doc, free))
            doc = []
            i = j + 1
            continue
        doc = []
        i += 1
    return fns


def docs_above(lines: list[str], i: int) -> list[str]:
    """The `///` lines of the item whose attributes include line `i`."""
    while i > 0 and lines[i - 1].strip().startswith("#["):
        i -= 1
    doc: list[str] = []
    while i > 0 and lines[i - 1].strip().startswith("///"):
        i -= 1
        doc.insert(0, lines[i].strip()[3:].strip())
    return doc


def block_end(lines: list[str], i: int) -> int:
    """The closing `}` at the indent of line `i` (rustfmt keeps these honest)."""
    indent = len(lines[i]) - len(lines[i].lstrip())
    closing = " " * indent + "}"
    for j in range(i + 1, len(lines)):
        if lines[j] in (closing, closing + ","):
            return j
    raise SystemExit(f"no end of block: {lines[i]}")


def next_item(lines: list[str], i: int) -> int:
    """The line after attributes and docs, from attribute line `i`."""
    i += 1
    while lines[i].strip().startswith(("#[", "///")):
        i += 1
    return i


def parse_enum(lines: list[str], i: int, doc: list[str], path: Path) -> Enum:
    m = re.match(r"pub enum (\w+) \{", lines[i])
    if not m:
        raise SystemExit(f"{path.name}: expected a pub enum: {lines[i]}")
    end = block_end(lines, i)
    variants: list[Variant] = []
    vdoc: list[str] = []
    j = i + 1
    while j < end:
        ln = lines[j].strip()
        if ln.startswith("///"):
            vdoc.append(ln[3:].strip())
        elif ln.startswith(("//", "#[")) or not ln:
            if ln.startswith("//"):
                vdoc = []
        elif vm := re.match(r"(\w+),$", ln):
            variants.append(Variant(vm.group(1), [], vdoc))
            vdoc = []
        # -- WP CG32 -- a tuple variant: its fields are UniFFI's v1, v2, ...
        elif vm := re.match(r"(\w+)\((.+)\),$", ln):
            types = [t.strip() for t in vm.group(2).split(",")]
            variants.append(Variant(vm.group(1), [Field(f"v{k + 1}", t) for k, t in enumerate(types)], vdoc))
            vdoc = []
        elif vm := re.match(r"(\w+) \{$", ln):
            fend = block_end(lines, j)
            fields: list[Field] = []
            fdoc: list[str] = []
            for fl in (x.strip() for x in lines[j + 1:fend]):
                if fl.startswith("///"):
                    fdoc.append(fl[3:].strip())
                elif fm := re.match(r"(\w+): (.+),$", fl):
                    fields.append(Field(fm.group(1), fm.group(2), fdoc))
                    fdoc = []
            variants.append(Variant(vm.group(1), fields, vdoc))
            vdoc = []
            j = fend
        else:
            raise SystemExit(f"{path.name}: cannot parse enum variant: {ln}")
        j += 1
    return Enum(m.group(1), variants, doc)


def parse_trait(lines: list[str], i: int, doc: list[str]) -> Iface:
    m = re.match(r"pub trait (\w+)", lines[i])
    if not m:
        raise SystemExit(f"expected a pub trait: {lines[i]}")
    end = block_end(lines, i)
    # A trait's methods end in `;` where an impl's have a body.
    body = [re.sub(r"^(\s*)fn ", r"\1pub fn ", ln.replace(";", " {") if ln.rstrip().endswith(";") else ln)
            for ln in lines[i + 1:end]]
    return Iface(m.group(1), parse_fns("\n".join(body), free=False), doc)


def parse_surface() -> Surface:
    out = Surface()
    # records.rs first: the big types read best at the top of CoreTypes.kt.
    # Recursive, so that an export in a submodule cannot go silently missing.
    files = sorted(
        CORE_SRC.rglob("*.rs"),
        key=lambda p: (p != CORE_SRC / "records.rs", p.relative_to(CORE_SRC).as_posix()),
    )
    for path in files:
        lines = path.read_text().splitlines()
        i = 0
        while i < len(lines):
            ln = lines[i].strip()
            m = re.match(r'#\[cfg_attr\(feature = "uniffi", (.+)\)\]$', ln)
            what = m.group(1) if m else ""
            if not what or what == "uniffi::constructor":
                i += 1
                continue
            doc = docs_above(lines, i)
            j = next_item(lines, i)
            if what == "derive(uniffi::Record)":
                end = block_end(lines, j)
                rec = parse_records("\n".join(lines[j:end + 1]))
                if len(rec) != 1:
                    raise SystemExit(f"{path.name}: expected one record at: {lines[j]}")
                rec[0].doc = doc
                out.records.append(rec[0])
                i = end
            elif what == "derive(uniffi::Enum)":
                out.enums.append(parse_enum(lines, j, doc, path))
                i = block_end(lines, j)
            elif what == "derive(uniffi::Error)":
                if out.error is not None:
                    raise SystemExit(f"{path.name}: a second exported error: {lines[j]}")
                out.error = parse_enum(lines, j, doc, path)
                i = block_end(lines, j)
            elif what == "derive(uniffi::Object)":
                name = re.match(r"pub struct (\w+)", lines[j])
                if not name:
                    raise SystemExit(f"{path.name}: expected a pub struct: {lines[j]}")
                if name.group(1) != "DspiCore":  # the contract itself
                    out.objects.setdefault(name.group(1), Iface(name.group(1), [], doc)).doc = doc
                i = j
            elif what == "uniffi::export(with_foreign)":
                t = parse_trait(lines, j, doc)
                out.traits[t.name] = t
                i = block_end(lines, j)
            elif what == "uniffi::export":
                if im := re.match(r"impl (\w+) \{", lines[j]):
                    end = block_end(lines, j)
                    fns = parse_fns("\n".join(lines[j + 1:end]), free=False)
                    if im.group(1) == "DspiCore":
                        out.methods += fns
                    else:
                        out.objects.setdefault(im.group(1), Iface(im.group(1), [], [])).methods += fns
                    i = end
                elif lines[j].startswith("pub fn "):
                    k = j
                    while "{" not in lines[k]:
                        k += 1
                    fn = parse_fns("\n".join(lines[j:k + 1]), free=True)
                    fn[0].doc = doc
                    out.free += fn
                    i = k
                else:
                    raise SystemExit(f"{path.name}: unknown export: {lines[j]}")
            else:
                raise SystemExit(f"{path.name}: unknown uniffi attribute: {ln}")
            i += 1
    if out.error is None:
        raise SystemExit("no exported error enum in the core")
    for e in out.enums:
        # -- WP CG26 -- An excluded enum is never generated.
        if e.name in EXCLUDED_ENUMS:
            continue
        # -- WP P0W -- a data-carrying enum is a sealed class (`gen_types`);
        # its fields are typed as on the domain side, fully qualified.
        for v in e.variants:
            for f in v.fields:
                if kt(f.ty) not in QUALIFIED:
                    raise SystemExit(f"enum {e.name}.{v.name}: field type {f.ty}: teach the generator")
    return apply_exclusions(out)


def apply_exclusions(s: Surface) -> Surface:
    for what, names, have in (("EXCLUDED_METHODS", EXCLUDED_METHODS, {f.name for f in s.methods + s.free}),
                              ("EXCLUDED_OBJECTS", EXCLUDED_OBJECTS, set(s.objects)),
                              ("EXCLUDED_TRAITS", EXCLUDED_TRAITS, set(s.traits)),
                              # -- WP CG26 --
                              ("EXCLUDED_ENUMS", EXCLUDED_ENUMS, {e.name for e in s.enums})):
        if stale := names - have:
            raise SystemExit(f"{what} has stale entries: {sorted(stale)}")
    s.methods = [f for f in s.methods if f.name not in EXCLUDED_METHODS]
    s.free = [f for f in s.free if f.name not in EXCLUDED_METHODS]
    s.objects = {k: v for k, v in s.objects.items() if k not in EXCLUDED_OBJECTS}
    s.traits = {k: v for k, v in s.traits.items() if k not in EXCLUDED_TRAITS}
    # -- WP CG26 --
    s.enums = [e for e in s.enums if e.name not in EXCLUDED_ENUMS]
    return s


PRIM = {
    "u8": "Int", "u16": "Int", "i8": "Int", "i16": "Int", "i32": "Int", "u32": "Long", "u64": "Long", "i64": "Long",
    "f32": "Float", "f64": "Double", "bool": "Boolean", "String": "String",
}
FFI_PRIM = {
    "u8": "UByte", "u16": "UShort", "i8": "Byte", "i16": "Short", "i32": "Int", "u32": "UInt", "u64": "ULong", "i64": "Long",
    "f32": "Float", "f64": "Double", "bool": "Boolean", "String": "String",
}


# -- WP P0W -- A sealed class's variants may shadow the Kotlin names
# (`ParamValue.Int`, `ParamValue.Float`), so its fields are written in full.
QUALIFIED = {
    "Int": "kotlin.Int", "Long": "kotlin.Long", "Float": "kotlin.Float", "Double": "kotlin.Double",
    "Boolean": "kotlin.Boolean", "String": "kotlin.String",
    "List<Int>": "kotlin.collections.List<kotlin.Int>",
}


def norm(t: str) -> str:
    return t.strip().replace("crate::", "").replace("&str", "String")


def unwrap_result(t: str) -> tuple[str, bool]:
    t = norm(t)
    m = re.match(r"Result<(.+)>$", t)
    if m:
        return m.group(1), True
    return t, False


def kt(t: str, name: str = "") -> str:
    t = norm(t)
    if t == "()":
        return "Unit"
    if t in PRIM:
        return PRIM[t]
    if t == "Vec<u8>":
        return "ByteArray" if name in RAW_BYTES else "List<Int>"
    if m := re.match(r"Vec<(.+)>$", t):
        return f"List<{kt(m.group(1))}>"
    if m := re.match(r"Option<(.+)>$", t):
        return f"{kt(m.group(1), name)}?"
    if m := re.match(r"Arc<(?:dyn )?(\w+)>$", t):
        return m.group(1)
    # -- WP P1NT -- the error as an argument (`notice_for`): its domain class.
    if t == "DspiError":
        return "DspiException"
    return t


def ffi_kt(t: str) -> str:
    """The UniFFI Kotlin type, for the parameters of a foreign trait's wrapper."""
    t = norm(t)
    if t == "Vec<u8>":
        return "ByteArray"
    if t in FFI_PRIM:
        return FFI_PRIM[t]
    if t == "()":
        return "Unit"
    if m := re.match(r"Vec<(.+)>$", t):
        return f"List<{ffi_kt(m.group(1))}>"
    if m := re.match(r"Option<(.+)>$", t):
        return f"{ffi_kt(m.group(1))}?"
    return f"{FFI}.{t}"


# ── expressions converting between domain and UniFFI values ─────────────


def to_ffi(expr: str, t: str, name: str = "") -> str:
    t = norm(t)
    if t in ("u8",):
        return f"{expr}.toUByte()"
    if t == "u16":
        return f"{expr}.toUShort()"
    if t == "i8":
        return f"{expr}.toByte()"
    if t == "i16":
        return f"{expr}.toShort()"
    if t == "u32":
        return f"{expr}.toUInt()"
    if t == "u64":
        return f"{expr}.toULong()"
    if t in PRIM:
        return expr
    if t == "Vec<u8>":
        return f"{expr}.copyOf()" if name in RAW_BYTES else f"ByteArray({expr}.size) {{ {expr}[it].toByte() }}"
    if m := re.match(r"Vec<(.+)>$", t):
        inner = to_ffi("it", m.group(1))
        return expr if inner == "it" else f"{expr}.map {{ {inner} }}"
    if m := re.match(r"Option<(.+)>$", t):
        inner = to_ffi("it", m.group(1), name)
        return expr if inner == "it" else f"{expr}?.let {{ {inner} }}"
    if m := re.match(r"Arc<dyn (\w+)>$", t):
        return f"wrap{m.group(1)}({expr})"
    return f"{expr}.toFfi()"


def to_dom(expr: str, t: str, name: str = "") -> str:
    t = norm(t)
    if t in ("u8", "u16", "i8", "i16"):
        return f"{expr}.toInt()"
    if t in ("u32", "u64"):
        return f"{expr}.toLong()"
    if t in PRIM or t == "()":
        return expr
    if t == "Vec<u8>":
        return f"{expr}.copyOf()" if name in RAW_BYTES else f"{expr}.map {{ it.toInt() and 0xFF }}"
    if m := re.match(r"Vec<(.+)>$", t):
        inner = to_dom("it", m.group(1))
        return expr if inner == "it" else f"{expr}.map {{ {inner} }}"
    if m := re.match(r"Option<(.+)>$", t):
        inner = to_dom("it", m.group(1), name)
        return expr if inner == "it" else f"{expr}?.let {{ {inner} }}"
    if m := re.match(r"Arc<(\w+)>$", t):
        return f"Ffi{m.group(1)}({expr})"
    return f"{expr}.toDomain()"


def shouty(s: str) -> str:
    """UniFFI's flat-enum variant name (heck's SHOUTY_SNAKE_CASE)."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", s).upper()


def kdoc(doc: list[str], indent: str) -> str:
    # A `/*` in a comment opens a nested comment in Kotlin.
    doc = [d.replace("/*", "/ *").replace("*/", "* /") for d in doc if d != "__ctor__"]
    if not doc:
        return ""
    body = "".join(f"{indent} * {d}\n".replace(" * \n", " *\n") for d in doc)
    return f"{indent}/**\n{body}{indent} */\n"


def gen_types(surf: Surface) -> str:
    out = [HEADER, "@file:Suppress(\"ArrayInDataClass\")\n\npackage se.bofr.dspi.core\n"]
    for r in surf.records:
        out.append("\n" + kdoc(r.doc, ""))
        out.append(f"data class {r.name}(\n")
        for f in r.fields:
            out.append(kdoc(f.doc, "    "))
            out.append(f"    val {camel(f.name)}: {kt(f.ty, f.name)},\n")
        out.append(")\n")
    for e in surf.enums:
        out.append("\n" + kdoc(e.doc, ""))
        if any(v.fields for v in e.variants):
            # -- WP P0W -- a data-carrying enum: a sealed class, as UniFFI makes it.
            out.append(f"sealed class {e.name} {{\n")
            for v in e.variants:
                out.append(kdoc(v.doc, "    "))
                if v.fields:
                    fs = ", ".join(f"val {camel(f.name)}: {QUALIFIED[kt(f.ty)]}" for f in v.fields)
                    out.append(f"    data class {v.name}({fs}) : {e.name}()\n")
                else:
                    out.append(f"    data object {v.name} : {e.name}()\n")
            out.append("}\n")
            continue
        out.append(f"enum class {e.name} {{\n")
        for v in e.variants:
            out.append(kdoc(v.doc, "    "))
            out.append(f"    {shouty(v.name)},\n")
        out.append("}\n")
    for o in surf.objects.values():
        out.append("\n" + kdoc(o.doc, ""))
        out.append(f"interface {o.name} : AutoCloseable {{\n")
        for f in o.methods:
            ret, throws = unwrap_result(f.ret) if f.ret else ("()", False)
            out.append(kdoc(f.doc, "    "))
            if throws:
                out.append("    @Throws(DspiException::class)\n")
            params = ", ".join(f"{camel(p.name)}: {kt(p.ty, p.name)}" for p in f.params)
            r = kt(ret)
            out.append(f"    fun {camel(f.name)}({params})" + ("" if r == "Unit" else f": {r}") + "\n")
        out.append("}\n")
    return "".join(out)


def gen_api(fns: list[Fn]) -> str:
    out = [HEADER, """
package se.bofr.dspi.core

/**
 * The DSPi core, 1:1 with what `crates/dspi-core` exports through UniFFI
 * (`DspiCore` methods + free functions; generator's EXCLUDED_* lists what
 * Android leaves out). Its doc comments, repeated below, are the semantics.
 *
 * Implementations: `FfiDspiCore` (:ffi, the real core over UniFFI) and
 * `FakeDspiCore` (:fake-core, tests and previews).
 *
 * Threading: every method may block on USB (≤ 1 s). Callers (the bridge) use
 * ONE serial background dispatcher; never call from the main thread.
 * Failures throw [DspiException]; [DspiException.Refused.status] carries the
 * device's code (see [DspiConstants]).
 *
 * Indices: channel = firmware wire index, output = output index, input =
 * input index — as in the core. App-id mapping is the bridge's job.
 */
interface DspiCoreApi : AutoCloseable {
"""]
    for f in fns:
        ret, throws = unwrap_result(f.ret) if f.ret else ("()", False)
        doc = list(f.doc)
        if f.free:
            doc.append("")
            doc.append("Stateless (a free function in dspi-core); needs no device.")
        out.append(kdoc(doc, "    "))
        if throws:
            out.append("    @Throws(DspiException::class)\n")
        params = ", ".join(f"{camel(p.name)}: {kt(p.ty, p.name)}" for p in f.params)
        r = kt(ret)
        out.append(f"    fun {camel(f.name)}({params})" + ("" if r == "Unit" else f": {r}") + "\n\n")
    out[-1] = out[-1].rstrip("\n") + "\n"
    out.append("}\n")
    return "".join(out)


def gen_wrapper(t: Iface) -> str:
    """`wrapX`: the domain listener as the UniFFI foreign trait."""
    body = []
    for f in t.methods:
        ret, throws = unwrap_result(f.ret) if f.ret else ("()", False)
        params = ", ".join(f"{camel(p.name)}: {ffi_kt(p.ty)}" for p in f.params)
        args = ", ".join(to_dom(camel(p.name), p.ty, p.name) for p in f.params)
        call = f"l.{camel(f.name)}({args})"
        conv = to_ffi(call, ret) if ret != "()" else call
        r = "" if ret == "()" else f": {ffi_kt(ret)}"
        if throws:
            body.append(f"            override fun {camel(f.name)}({params}){r} =\n"
                        f"                try {{\n                    {conv}\n"
                        "                } catch (e: DspiException) {\n                    throw e.toFfi()\n                }\n")
        else:
            body.append(f"            override fun {camel(f.name)}({params}){r} = {conv}\n")
    joined = "\n".join(body)
    return (f"\n    private fun wrap{t.name}(l: {t.name}) =\n"
            f"        object : {FFI}.{t.name} {{\n{joined}        }}\n")


def gen_error(err: Enum) -> str:
    """Both directions, one `when` arm per variant: a new variant of the core's
    error fails the build until `DspiException.kt` has its class."""
    dom, ffi = [], []
    for v in err.variants:
        doms = ", ".join(to_dom(camel(f.name), f.ty, f.name) for f in v.fields)
        ffis = ", ".join(to_ffi(camel(f.name), f.ty, f.name) for f in v.fields)
        dom.append(f"        is FfiException.{v.name} -> DspiException.{v.name}({doms})\n")
        ffi.append(f"        is DspiException.{v.name} -> FfiException.{v.name}({ffis})\n")
    return ("internal fun FfiException.toDomain(): DspiException =\n    when (this) {\n" + "".join(dom) + "    }\n\n"
            "internal fun DspiException.toFfi(): FfiException =\n    when (this) {\n" + "".join(ffi) + "    }\n")


def gen_adapter(surf: Surface) -> str:
    fns = surf.methods + surf.free
    out = [HEADER, """
package se.bofr.dspi.ffi

import se.bofr.dspi.core.*
import se.bofr.dspi.ffi.uniffi.DspiCore as FfiCore
import se.bofr.dspi.ffi.uniffi.DspiException as FfiException

/**
 * [DspiCoreApi] over the UniFFI-generated bindings of `libdspi_ffi.so`.
 * Pure delegation + type mapping; all behaviour lives in Rust.
 */
class FfiDspiCore : DspiCoreApi {
    private val core = FfiCore()

    override fun close() = core.close()

    private inline fun <T> call(block: () -> T): T =
        try {
            block()
        } catch (e: FfiException) {
            throw e.toDomain()
        }
"""]
    for t in surf.traits.values():
        out.append(gen_wrapper(t))
    out.append("""
    companion object {
        init {
            System.loadLibrary("dspi_ffi")
            se.bofr.dspi.ffi.uniffi.logging.initLogging()
        }
    }
""")
    for f in fns:
        ret, throws = unwrap_result(f.ret) if f.ret else ("()", False)
        params = ", ".join(f"{camel(p.name)}: {kt(p.ty, p.name)}" for p in f.params)
        args = ", ".join(to_ffi(camel(p.name), p.ty, p.name) for p in f.params)
        target = f"{FFI}.{camel(f.name)}({args})" if f.free else f"core.{camel(f.name)}({args})"
        r = kt(ret)
        body = to_dom(target, ret)
        sig = f"    override fun {camel(f.name)}({params})" + ("" if r == "Unit" else f": {r}")
        if throws:
            out.append(f"\n{sig} = call {{ {body} }}\n")
        else:
            out.append(f"\n{sig} = {body}\n")
    out.append("}\n")
    for o in surf.objects.values():
        out.append(f"\ninternal class Ffi{o.name}(private val inner: {FFI}.{o.name}) : {o.name} {{\n")
        out.append("    override fun close() = inner.close()\n")
        for f in o.methods:
            ret, throws = unwrap_result(f.ret) if f.ret else ("()", False)
            if throws:
                raise SystemExit(f"{o.name}.{f.name}: a throwing object method: teach the generator")
            params = ", ".join(f"{camel(p.name)}: {kt(p.ty, p.name)}" for p in f.params)
            args = ", ".join(to_ffi(camel(p.name), p.ty, p.name) for p in f.params)
            r = kt(ret)
            sig = f"    override fun {camel(f.name)}({params})" + ("" if r == "Unit" else f": {r}")
            out.append(f"\n{sig} = {to_dom(f'inner.{camel(f.name)}({args})', ret)}\n")
        out.append("}\n")
    out.append("\n// ── Error mapping ──\n\n")
    out.append(gen_error(surf.error))
    out.append("\n// ── Record mapping (UniFFI <-> domain) ──\n")
    for r in surf.records:
        fields_d = ",\n".join(f"        {camel(f.name)} = {to_dom(camel(f.name), f.ty, f.name)}" for f in r.fields)
        fields_f = ",\n".join(f"        {camel(f.name)} = {to_ffi(camel(f.name), f.ty, f.name)}" for f in r.fields)
        out.append(f"\ninternal fun {FFI}.{r.name}.toDomain() =\n    {r.name}(\n{fields_d},\n    )\n")
        out.append(f"\ninternal fun {r.name}.toFfi() =\n    {FFI}.{r.name}(\n{fields_f},\n    )\n")
    out.append("\n// ── Enum mapping ──\n")
    for e in surf.enums:
        if any(v.fields for v in e.variants):
            # -- WP P0W -- a sealed class: one arm per variant, fields converted.
            def arm(v: Variant, src: str, dst: str, conv) -> str:
                if not v.fields:
                    return f"        is {src}.{v.name} -> {dst}.{v.name}\n"
                args = ", ".join(conv(camel(f.name), f.ty, f.name) for f in v.fields)
                return f"        is {src}.{v.name} -> {dst}.{v.name}({args})\n"
            arms_d = "".join(arm(v, f"{FFI}.{e.name}", e.name, to_dom) for v in e.variants)
            arms_f = "".join(arm(v, e.name, f"{FFI}.{e.name}", to_ffi) for v in e.variants)
            out.append(f"\ninternal fun {FFI}.{e.name}.toDomain(): {e.name} =\n    when (this) {{\n{arms_d}    }}\n")
            out.append(f"\ninternal fun {e.name}.toFfi(): {FFI}.{e.name} =\n    when (this) {{\n{arms_f}    }}\n")
            continue
        arms_d = "".join(f"        {FFI}.{e.name}.{shouty(v.name)} -> {e.name}.{shouty(v.name)}\n" for v in e.variants)
        arms_f = "".join(f"        {e.name}.{shouty(v.name)} -> {FFI}.{e.name}.{shouty(v.name)}\n" for v in e.variants)
        out.append(f"\ninternal fun {FFI}.{e.name}.toDomain(): {e.name} =\n    when (this) {{\n{arms_d}    }}\n")
        out.append(f"\ninternal fun {e.name}.toFfi(): {FFI}.{e.name} =\n    when (this) {{\n{arms_f}    }}\n")
    return "".join(out)


def gen_unimpl(fns: list[Fn]) -> str:
    out = [HEADER, """
package se.bofr.dspi.core

/**
 * Base [DspiCoreApi] for test doubles: every method throws
 * [NotImplementedError]. Doubles extend it and override what they support,
 * so they keep compiling when the contract grows. Test helper only (no
 * production class extends it).
 */
open class UnimplementedDspiCore : DspiCoreApi {
    override fun close() {}
"""]
    for f in fns:
        ret, _ = unwrap_result(f.ret) if f.ret else ("()", False)
        params = ", ".join(f"{camel(p.name)}: {kt(p.ty, p.name)}" for p in f.params)
        r = kt(ret)
        sig = f"    override fun {camel(f.name)}({params})" + ("" if r == "Unit" else f": {r}")
        out.append(f"\n{sig}: Unit = throw NotImplementedError(\"{f.name}\")\n" if r == "Unit"
                   else f"\n{sig} = throw NotImplementedError(\"{f.name}\")\n")
    out.append("}\n")
    return "".join(out)


CONST_RX = re.compile(r"^pub const ([A-Z0-9_]+): ([a-z0-9]+) = (.+);")
LITERAL_RX = re.compile(r"-?(0x[0-9A-Fa-f_]+|[0-9][0-9_]*(\.[0-9]+)?)( << [0-9]+)?$")


def parse_consts(path: Path) -> list[tuple[str, str, str, str, list[str]]]:
    """(group, name, type, value, doc) per scalar `pub const`, in file order."""
    out = []
    group = path.name
    doc: list[str] = []
    for ln in path.read_text().splitlines():
        st = ln.strip()
        if m := re.match(r"// ── (\S+)", ln):
            group = m.group(1)
        if ln.startswith("///"):
            doc.append(st[3:].strip())
            continue
        if ln.startswith("#[cfg(test)]"):
            break
        if m := CONST_RX.match(ln):
            out.append((group, m.group(1), m.group(2), m.group(3), doc))
        elif ln.startswith("pub const ") and ln.rstrip().endswith("="):
            raise SystemExit(f"{path.name}: a const on two lines, teach the generator: {ln}")
        doc = []
    return out


def gen_consts() -> str:
    # The C header's list holds every old-core constant, literally. dspi-core's
    # consts.rs adds what is newer; many of its values are expressions over the
    # firmware-generated ones, which only cargo can evaluate. Those must also be
    # in the C header's list (whose test holds the two together).
    capi = parse_consts(CAPI_CONSTS)
    known = {c[1]: c for c in capi}
    newer = []
    for c in parse_consts(CORE_CONSTS):
        name, val = c[1], c[3]
        if name in known:
            if LITERAL_RX.match(val) and int_or_str(val) != int_or_str(known[name][3]):
                raise SystemExit(f"{name}: dspi-core has {val}, dspi-capi {known[name][3]}")
        elif LITERAL_RX.match(val):
            newer.append(c)
        else:
            raise SystemExit(f"{name} = {val}: not a literal and not in dspi-capi's consts.rs")
    seen: set[str] = set()
    groups: dict[str, list[str]] = {}
    opcodes: list[str] = []
    for group, name, ty, val, doc in capi + [("dspi-core consts.rs", *c[1:]) for c in newer]:
        if name in seen:
            raise SystemExit(f"duplicate const {name}")
        seen.add(name)
        val = val.replace("<<", "shl")
        if ty in ("f32", "f64"):
            kty, val = ("Float", val + "f") if ty == "f32" else ("Double", val)
        elif ty in ("u64", "i64"):
            kty, val = "Long", val + "L"
        else:
            kty = "Int"
        entry = kdoc(doc, "    ") + f"    const val {name}: {kty} = {val}\n"
        if name.startswith("REQ_"):
            opcodes.append(entry)
        else:
            groups.setdefault(group, []).append(entry)
    # Opcodes newer than the old core: only the vendored firmware header names them.
    for name, val in re.findall(r"^#define (REQ_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|\d+)", FIRMWARE_CONFIG.read_text(), re.M):
        if name not in seen:
            seen.add(name)
            opcodes.append(f"    const val {name}: Int = {val}\n")
    out = [HEADER.replace("from crates/dspi-core", "from crates/dspi-capi, dspi-core consts.rs and dspi-proto's config.h"), """
@file:Suppress("unused")

package se.bofr.dspi.core

/**
 * Every scalar constant of the core (except `REQ_*`, see [Opcodes]), same names
 * and values. Use these instead of magic numbers.
 */
object DspiConstants {
"""]
    for group, lines in groups.items():
        out.append(f"    // ── {group} ──\n")
        out.extend(lines)
        out.append("\n")
    out.append("    // ── firmware config.h (not in the core; FIRMWARE_CONSTS) ──\n")
    for name, val, doc in FIRMWARE_CONSTS:
        if name in seen:
            raise SystemExit(f"FIRMWARE_CONSTS {name} now exists in the core; drop it")
        out.append(f"    /** {doc} */\n    const val {name}: Int = {val}\n")
    out.append("}\n\n/** Vendor request opcodes (`REQ_*`), for the monitor and coverage tooling. */\nobject Opcodes {\n")
    out.extend(opcodes)
    out.append("}\n")
    return "".join(out)


def int_or_str(v: str):
    """A literal's value, so `0xFF`, `255` and `1 << 10` compare by value."""
    v = v.replace("_", "")
    try:
        if "<<" in v:
            a, b = v.split("<<")
            return int(a.strip(), 0) << int(b)
        return int(v, 0)
    except ValueError:
        return float(v)


def missing_listeners(surf) -> list[str]:
    """-- WP HUBADMINF -- the foreign traits with no `interface`/`fun interface` of that
    name in Listeners.kt."""
    text = LISTENERS.read_text() if LISTENERS.exists() else ""
    return sorted(n for n in surf.traits
                  if not re.search(rf"^\s*(?:fun\s+)?interface\s+{re.escape(n)}\b", text, re.M))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    a = ap.parse_args()
    surf = parse_surface()
    fns = surf.methods + surf.free
    outputs = {
        OUT_TYPES: gen_types(surf),
        OUT_API: gen_api(fns),
        OUT_ADAPTER: gen_adapter(surf),
        OUT_CONSTS: gen_consts(),
        OUT_UNIMPL: gen_unimpl(fns),
    }
    stale = []
    for path, text in outputs.items():
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    # -- WP HUBADMINF -- a foreign trait without its hand-written interface fails
    # here, not first in the Kotlin compile
    missing = missing_listeners(surf)
    for name in missing:
        print(f"missing: interface {name} in {LISTENERS.relative_to(ROOT)} (hand-written; the "
              f"generated code names it)", file=sys.stderr)
    if stale:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run tools/gen_kotlin_contract.py)", file=sys.stderr)
        return 1
    if missing:
        return 1
    print(f"records={len(surf.records)} enums={len(surf.enums)} methods={len(surf.methods)} free={len(surf.free)} "
          f"errors={len(surf.error.variants)} traits={len(surf.traits)} objects={len(surf.objects)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
