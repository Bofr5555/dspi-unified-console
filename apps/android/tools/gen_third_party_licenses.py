#!/usr/bin/env python3
"""Generate the third-party notices for the Rust side of the app.

Writes feature-settings/src/main/assets/licenses/rust-crates.txt: every crate
in the normal-dependency closure of crates/dspi-ffi for the Android target, with
the features the Android build uses, with its licence expression and the verbatim
licence/notice files it ships (identical texts printed once and referenced
afterwards). Run in the container (needs cargo and the populated cargo registry):

    tools/dev.sh python3 tools/gen_third_party_licenses.py

tools/ci.sh settings (and tools/ci.sh licenses) re-run it with --check, which fails when
the committed file is stale.
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOP = ROOT.parent.parent
OUT = ROOT / "feature-settings/src/main/assets/licenses/rust-crates.txt"
TARGET = "aarch64-linux-android"  # the other ABIs resolve to the same crate set
OWN_CRATES = ("dspi-ffi", "dspi-core", "dspi-link", "dspi-proto", "dspi-session", "dspi-transport")
NOTICE_GLOBS = ("LICENSE*", "LICENCE*", "COPYING*", "NOTICE*", "UNLICENSE*", "COPYRIGHT*")


def crate_closure():
    # `cargo metadata` resolves the whole workspace with its members' features, so
    # it also lists what only the desktop apps pull in (mdns-sd, midir). `cargo tree`
    # resolves dspi-ffi alone: exactly what the library links.
    tree = subprocess.check_output(
        ["cargo", "tree", "--locked", "-p", "dspi-ffi", "--target", TARGET, "-e", "normal",
         "--prefix", "none", "--no-dedupe", "-f", "{p}"],
        cwd=TOP, text=True)
    wanted = {tuple(ln.split()[:2]) for ln in tree.splitlines() if ln.strip()}
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
        cwd=TOP))
    pkgs = [p for p in meta["packages"] if (p["name"], "v" + p["version"]) in wanted]
    missing = wanted - {(p["name"], "v" + p["version"]) for p in pkgs}
    if missing:
        sys.exit(f"cargo tree lists crates cargo metadata does not: {sorted(missing)}")
    return sorted(pkgs, key=lambda p: (p["name"], p["version"]))


def notice_files(pkg):
    d = Path(pkg["manifest_path"]).parent
    return sorted({f for g in NOTICE_GLOBS for f in d.glob(g) if f.is_file()})


def main():
    out, texts = [], {}
    out.append("Third-party Rust crates linked into libdspi_ffi.so\n")
    out.append("Generated by tools/gen_third_party_licenses.py — do not edit.\n")
    out.append("Where a crate offers a choice (\"MIT OR Apache-2.0\"), this app uses it under the\n"
               "licence compatible with GPL-3.0 (MIT or Apache-2.0).\n\n")
    for p in crate_closure():
        if p["name"] in OWN_CRATES:
            continue  # this project's own: listed on the Licences screen itself
        lic = p.get("license") or "(see files)"
        repo = p.get("repository") or ""
        out.append("=" * 72 + "\n")
        out.append(f"{p['name']} {p['version']} — {lic}\n{repo}\n")
        for f in notice_files(p):
            body = f.read_text(errors="replace").strip() + "\n"
            h = hashlib.sha256(body.encode()).hexdigest()[:12]
            rel = f.relative_to(Path(p["manifest_path"]).parent)
            if h in texts:
                out.append(f"\n[{rel}: same text as {texts[h]}]\n")
            else:
                texts[h] = f"{p['name']} {p['version']}/{rel}"
                out.append(f"\n--- {rel} ---\n{body}")
        out.append("\n")
    text = "".join(out)
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: run tools/gen_third_party_licenses.py")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
