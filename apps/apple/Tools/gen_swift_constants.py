#!/usr/bin/env python3
"""Generate DspiConstants.swift, the core's constants for the Swift app (WP SW25).

The same constants as the Android contract's DspiConstants.kt, read the same way
(apps/android/tools/gen_kotlin_contract.py, whose parser this imports):

Reads   crates/dspi-capi/src/types/consts.rs  every old-core constant, as literals
        crates/dspi-core/src/consts.rs        the newer ones (NOTIFY_DISCONNECTED, ...)
        crates/dspi-proto/firmware/config.h   `REQ_*` opcodes newer than those, and the
                                              extension channel's `EXT_*` sub-commands
        crates/dspi-proto/firmware/notify.h   `NOTIFY_EVT_*` event codes, `NOTIFY_FEAT_*`
        crates/dspi-link/src/frames.rs, lib.rs, messages.rs
                                              DSPi Link frame kinds, CMD statuses, port
Writes  the file named on the command line: ci/drift.sh writes ci/generated/swift/
        DspiConstants.swift and the app's copy, Core/Generated/Sources/dspi_constants/.

Types follow the Rust ones (u8 -> UInt8, u16 -> UInt16, u32 -> UInt32, i64 -> Int64,
usize -> Int, f32 -> Float, f64 -> Double), so a value goes on the wire without a
conversion. From the firmware headers: REQ_* and NOTIFY_EVT_* UInt8, EXT_* UInt16
(the wValue), NOTIFY_FEAT_* UInt32.

  gen_swift_constants.py OUT        write the file
  gen_swift_constants.py --compare-app
                                    list the app's hand-written top-level constants
                                    (`let NAME: T = literal`) against the generated
                                    ones: same value, different value, not in the core
"""
from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

TOP = Path(__file__).resolve().parents[3]
_spec = importlib.util.spec_from_file_location(
    "gen_kotlin_contract", TOP / "apps/android/tools/gen_kotlin_contract.py")
assert _spec and _spec.loader
kc = importlib.util.module_from_spec(_spec)
sys.modules[_spec.name] = kc  # its dataclasses look themselves up there
sys.dont_write_bytecode = True  # no __pycache__ in apps/android/tools
_spec.loader.exec_module(kc)

NOTIFY_H = TOP / "crates/dspi-proto/firmware/notify.h"
LINK_SRC = TOP / "crates/dspi-link/src"
# DSPi Link: (file, `pub mod` holding the consts or None for top level, Swift prefix).
LINK_CONSTS = [("frames.rs", "kind", "KIND_"), ("frames.rs", "status", "STATUS_"),
               ("lib.rs", None, ""), ("messages.rs", None, "")]
APP = TOP / "apps/apple/DSPi Console"
HEADER = """\
// GENERATED by apps/apple/Tools/gen_swift_constants.py from crates/dspi-capi,
// dspi-core consts.rs and dspi-proto's firmware headers — do not edit.
// Regenerate: ci/run.sh 'ci/drift.sh write' (WP SW25).
"""
SWIFT_TYPE = {"u8": "UInt8", "u16": "UInt16", "u32": "UInt32", "u64": "UInt64",
              "i8": "Int8", "i16": "Int16", "i32": "Int32", "i64": "Int64",
              "usize": "Int", "f32": "Float", "f64": "Double"}
# Firmware header prefixes, with the Swift type of their values.
HEADER_PREFIXES = [(kc.FIRMWARE_CONFIG, "EXT_", "UInt16"),
                   (NOTIFY_H, "NOTIFY_EVT_", "UInt8"), (NOTIFY_H, "NOTIFY_FEAT_", "UInt32")]
DEFINE_RX = re.compile(r"^#define ([A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|\d+|\(1u << \d+\))\s*(?://\s*(.*))?$", re.M)


def doc_lines(doc: list[str], indent: str) -> str:
    return "".join(f"{indent}/// {d}".rstrip() + "\n" for d in doc)


def collect() -> tuple[dict[str, list[tuple[str, str, str, list[str]]]], list[tuple[str, str, str, list[str]]]]:
    """({group: [(name, swift type, value, doc)]}, opcodes), the selection of
    gen_kotlin_contract.gen_consts with the same consistency checks."""
    capi = kc.parse_consts(kc.CAPI_CONSTS)
    known = {c[1]: c for c in capi}
    newer = []
    for c in kc.parse_consts(kc.CORE_CONSTS):
        name, val = c[1], c[3]
        if name in known:
            if kc.LITERAL_RX.match(val) and kc.int_or_str(val) != kc.int_or_str(known[name][3]):
                raise SystemExit(f"{name}: dspi-core has {val}, dspi-capi {known[name][3]}")
        elif kc.LITERAL_RX.match(val):
            newer.append(c)
        else:
            raise SystemExit(f"{name} = {val}: not a literal and not in dspi-capi's consts.rs")
    seen: set[str] = set()
    groups: dict[str, list] = {}
    opcodes: list = []
    for group, name, ty, val, doc in capi + [("dspi-core consts.rs", *c[1:]) for c in newer]:
        if name in seen:
            raise SystemExit(f"duplicate const {name}")
        seen.add(name)
        if ty not in SWIFT_TYPE:
            raise SystemExit(f"{name}: no Swift type for {ty}")
        entry = (name, SWIFT_TYPE[ty], val, doc)
        (opcodes if name.startswith("REQ_") else groups.setdefault(group, [])).append(entry)
    config = kc.FIRMWARE_CONFIG.read_text()
    for name, val in re.findall(r"^#define (REQ_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|\d+)", config, re.M):
        if name not in seen:
            seen.add(name)
            opcodes.append((name, "UInt8", val, []))
    for name, val, doc in kc.FIRMWARE_CONSTS:
        if name in seen:
            raise SystemExit(f"FIRMWARE_CONSTS {name} now exists in the core; drop it")
        seen.add(name)
        groups.setdefault("firmware config.h (not in the core)", []).append((name, "UInt8", val, [doc]))
    for path, prefix, sty in HEADER_PREFIXES:
        group = f"firmware {path.name}"
        for name, val, comment in DEFINE_RX.findall(path.read_text()):
            if not name.startswith(prefix):
                continue
            if name in seen:
                raise SystemExit(f"{name} from {path.name} is also in the core")
            seen.add(name)
            val = re.sub(r"\(1u << (\d+)\)", r"1 << \1", val)
            groups.setdefault(group, []).append((name, sty, val, [comment] if comment else []))
    return groups, opcodes


def collect_link() -> list[tuple[str, str, str, list[str]]]:
    """DSPi Link's scalar constants: (name, swift type, value, doc)."""
    out = []
    for file, mod, prefix in LINK_CONSTS:
        lines = (LINK_SRC / file).read_text().splitlines()
        if mod is not None:
            # The module's body, de-indented: from `pub mod m {` to its closing `}`.
            start = lines.index(f"pub mod {mod} {{") + 1
            lines = [ln.removeprefix("    ") for ln in lines[start:lines.index("}", start)]]
        doc: list[str] = []
        for ln in lines:
            if ln.startswith("#[cfg(test)]"):
                break
            if ln.startswith("///"):
                doc.append(ln[3:].strip())
                continue
            # Scalar consts only: `&str` and `Duration` ones do not match.
            if m := kc.CONST_RX.match(ln):
                name, ty, val = m.groups()
                if ty not in SWIFT_TYPE or not kc.LITERAL_RX.match(val):
                    raise SystemExit(f"dspi-link {file}: {name}: {ty} = {val} is not a scalar literal")
                out.append((prefix + name, SWIFT_TYPE[ty], val, doc))
            doc = []
    names = [e[0] for e in out]
    if len(set(names)) != len(names):
        raise SystemExit("dspi-link: duplicate constant names")
    return out


def generate() -> str:
    groups, opcodes = collect()
    out = [HEADER, """
/// Every scalar constant of the core (except `REQ_*`, see `Opcodes`), same names,
/// values and widths as in Rust, and the firmware's extension and notification
/// codes. Use these instead of magic numbers.
public enum DspiConstants {
"""]
    for group, entries in groups.items():
        out.append(f"    // ── {group} ──\n")
        for name, sty, val, doc in entries:
            out.append(doc_lines(doc, "    ") + f"    public static let {name}: {sty} = {val}\n")
        out.append("\n")
    out[-1] = "}\n"
    out.append("\n/// Vendor request opcodes (`REQ_*`, the bRequest byte).\npublic enum Opcodes {\n")
    for name, sty, val, doc in opcodes:
        out.append(doc_lines(doc, "    ") + f"    public static let {name}: {sty} = {val}\n")
    out.append("}\n")
    out.append("\n/// DSPi Link (crates/dspi-link): frame kinds (`KIND_*`, spec 8), CMD response\n"
               "/// statuses (`STATUS_*`, spec 8.1), the default port and the protocol version.\n"
               "public enum LinkConstants {\n")
    for name, sty, val, doc in collect_link():
        out.append(doc_lines(doc, "    ") + f"    public static let {name}: {sty} = {val}\n")
    out.append("}\n")
    return "".join(out)


APP_LET_RX = re.compile(r"^let ([A-Z][A-Z0-9_]+)\s*:\s*(\w+)\s*=\s*([^/\n]+?)\s*(?://.*)?$", re.M)


def compare_app() -> int:
    groups, opcodes = collect()
    gen = {n: v for es in [*groups.values(), opcodes] for n, _, v, _ in es}
    same, differ, absent = [], [], []
    for path in sorted(APP.rglob("*.swift")):
        if "Generated" in path.parts:
            continue
        for name, sty, val in APP_LET_RX.findall(path.read_text()):
            where = f"{path.relative_to(APP)}"
            if name not in gen:
                absent.append(f"{name} ({where})")
                continue
            try:
                ok = kc.int_or_str(val.replace(" ", "")) == kc.int_or_str(gen[name].replace(" ", ""))
            except ValueError:
                ok = False
            (same if ok else differ).append(f"{name} ({where}): app {val}, core {gen[name]}")
    print(f"same value: {len(same)}")
    for s in same:
        print(f"  {s}")
    print(f"different value or not comparable: {len(differ)}")
    for s in differ:
        print(f"  {s}")
    print(f"not in the core: {len(absent)}")
    for s in absent:
        print(f"  {s}")
    return 0


def main() -> int:
    if sys.argv[1:] == ["--compare-app"]:
        return compare_app()
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    Path(sys.argv[1]).write_text(generate())
    return 0


if __name__ == "__main__":
    sys.exit(main())
