#!/usr/bin/env python3
"""The third-party notices of the Rust crates in the web console's core (WP WB7).

Writes apps/web/notices/rust-crates.txt: every crate linked into dspi_wasm.wasm
(the normal, non-proc-macro closure of crates/dspi-wasm for wasm32-unknown-unknown),
its licence expression and the licence and notice files it ships, identical texts
printed once. tools/build.mjs puts it into dist/THIRD-PARTY-NOTICES.txt with the
JavaScript side (Preact). Adapted from apps/android/tools/gen_third_party_licenses.py.
Runs in the cross container (cargo and the crate registry):

    DSPI_PROFILE=cross ci/run.sh 'python3 apps/web/tools/gen_rust_notices.py'
    DSPI_PROFILE=cross ci/run.sh 'python3 apps/web/tools/gen_rust_notices.py --check'

apps/web/tools/ci.sh runs --check, which fails when the committed file is stale.
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

TOP = Path(__file__).resolve().parents[3]
OUT = TOP / "apps/web/notices/rust-crates.txt"
TARGET = "wasm32-unknown-unknown"
NOTICE_GLOBS = ("LICENSE*", "LICENCE*", "COPYING*", "NOTICE*", "UNLICENSE*", "COPYRIGHT*")


def crate_closure():
    tree = subprocess.check_output(
        ["cargo", "tree", "--locked", "-p", "dspi-wasm", "--target", TARGET, "-e", "normal,no-proc-macro",
         "--prefix", "none", "--no-dedupe", "-f", "{p}"],
        cwd=TOP, text=True)
    wanted = {tuple(ln.split()[:2]) for ln in tree.splitlines() if ln.strip()}
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
        cwd=TOP))
    pkgs = [p for p in meta["packages"] if (p["name"], "v" + p["version"]) in wanted]
    missing = wanted - {(p["name"], "v" + p["version"]) for p in pkgs}
    if missing:
        sys.exit(f"cargo tree lists crates cargo metadata does not: {sorted(missing)}")
    return sorted(pkgs, key=lambda p: (p["name"], p["version"]))


def notice_files(pkg):
    d = Path(pkg["manifest_path"]).parent
    return sorted({f for g in NOTICE_GLOBS for f in d.glob(g) if f.is_file()})


def main():
    out, texts = [], {}
    out.append("Third-party Rust crates linked into dspi_wasm.wasm (the console's core)\n")
    out.append("Generated by apps/web/tools/gen_rust_notices.py; do not edit.\n")
    out.append("Where a crate offers a choice (\"MIT OR Apache-2.0\"), this console uses it under the\n"
               "licence compatible with GPL-3.0 (MIT or Apache-2.0).\n\n")
    for p in crate_closure():
        # This project's own (dspi-*): the console's GPL, linked from About.
        if Path(p["manifest_path"]).resolve().is_relative_to(TOP):
            continue
        lic = p.get("license") or "(see files)"
        repo = p.get("repository") or ""
        out.append("=" * 72 + "\n")
        out.append(f"{p['name']} {p['version']} — {lic}\n{repo}\n")
        for f in notice_files(p):
            body = f.read_text(errors="replace").strip() + "\n"
            h = hashlib.sha256(body.encode()).hexdigest()[:12]
            rel = f.relative_to(Path(p["manifest_path"]).parent)
            if h in texts:
                out.append(f"\n[{rel}: same text as {texts[h]}]\n")
            else:
                texts[h] = f"{p['name']} {p['version']}/{rel}"
                out.append(f"\n--- {rel} ---\n{body}")
        out.append("\n")
    text = "".join(out)
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(TOP)} is stale: run apps/web/tools/gen_rust_notices.py")
        print(f"{OUT.relative_to(TOP)}: up to date")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(TOP)} ({len(text)} bytes)")


if __name__ == "__main__":
    main()
